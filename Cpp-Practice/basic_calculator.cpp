#include <iostream>
using namespace std;

int main() {
    double n1 , n2;

    cout << "Enter first number: " ;
    cin >> n1; 
    cout<< "Enter 2nd number: " ;
    cin >> n2;

    cout << "Sum of 2 number is: " << n1 + n2 << endl;
    cout << "Multiplication of 2 number is: " << n1 * n2 << endl;
    cout << "Subtraction of 2 number is: " << n1 - n2 << endl;
    cout << "Division of 2 number is: " << n1 / n2 << endl;

    return 0;
}